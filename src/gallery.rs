//! Registered media in `%LOCALAPPDATA%\atmos-lcd\gallery\<id>\`:
//!   frames.bin    unrotated 480x480 JPEG frames with delays (see `FrameFile`)
//!   rot<deg>.bin  the same rotated by a non-90-degree remainder, made on demand
//!   thumb.jpg     small preview for the gallery grid
//!   info.txt      `key=value` metadata
//!
//! Converting runs in a child process (`atmos-lcd import ...`) so the decoder,
//! GPU driver and scratch buffers never stay in the long-running app.

use std::fs::{self, File};
use std::io::{self, BufRead, BufReader, Read, Write};
use std::os::windows::fs::FileExt;
use std::os::windows::process::CommandExt;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::time::{Duration, SystemTime, UNIX_EPOCH};

use image::imageops::FilterType;
use tiny_skia::Pixmap;

use crate::media::{self, Media};
use crate::render;

const MAGIC: &[u8; 4] = b"ATF1";
const THUMB_SIZE: u32 = 160;
/// Keeps the child process from flashing a console window.
const CREATE_NO_WINDOW: u32 = 0x0800_0000;

#[derive(Clone, Debug)]
pub struct Item {
    pub id: String,
    pub name: String,
    pub frames: usize,
    pub duration: Duration,
    pub bytes: u64,
}

impl Item {
    pub fn is_animated(&self) -> bool {
        self.frames > 1
    }
}

pub fn root() -> PathBuf {
    let base = std::env::var_os("LOCALAPPDATA").map(PathBuf::from).unwrap_or_else(|| ".".into());
    base.join("atmos-lcd").join("gallery")
}

fn item_dir(id: &str) -> PathBuf {
    root().join(id)
}

pub fn thumb_path(id: &str) -> PathBuf {
    item_dir(id).join("thumb.jpg")
}

/// The frame file for `id` with `extra_rotation` (degrees, 0..90) applied.
pub fn frames_path(id: &str, extra_rotation: u16) -> PathBuf {
    match extra_rotation {
        0 => item_dir(id).join("frames.bin"),
        r => item_dir(id).join(format!("rot{r}.bin")),
    }
}

/// All items, oldest first. Unreadable entries (e.g. an import in progress) are skipped.
pub fn list() -> Vec<Item> {
    let Ok(entries) = fs::read_dir(root()) else { return Vec::new() };
    let mut items: Vec<(u64, Item)> = entries
        .flatten()
        .filter_map(|e| {
            let id = e.file_name().to_string_lossy().into_owned();
            let text = fs::read_to_string(e.path().join("info.txt")).ok()?;
            let get = |key: &str| text.lines().find_map(|l| l.strip_prefix(key)?.strip_prefix('='));
            let item = Item {
                name: get("name").unwrap_or(&id).to_string(),
                frames: get("frames")?.parse().ok()?,
                duration: Duration::from_millis(get("duration_ms")?.parse().ok()?),
                bytes: get("bytes")?.parse().ok()?,
                id,
            };
            Some((get("added").and_then(|a| a.parse().ok()).unwrap_or(0), item))
        })
        .collect();
    items.sort_by_key(|(added, _)| *added);
    items.into_iter().map(|(_, item)| item).collect()
}

pub fn remove(id: &str) -> io::Result<()> {
    // Ids are generated by us; refuse anything that could escape the gallery folder.
    if id.is_empty() || !id.chars().all(|c| c.is_ascii_alphanumeric()) {
        return Err(io::Error::new(io::ErrorKind::InvalidInput, "bad gallery id"));
    }
    fs::remove_dir_all(item_dir(id))
}

fn new_id() -> String {
    let nanos = SystemTime::now().duration_since(UNIX_EPOCH).unwrap_or_default().as_nanos();
    format!("{nanos:x}")
}

/// Runs the import in a child process. `progress` receives 0.0..=1.0; returns the new id.
pub fn import(source: &Path, mut progress: impl FnMut(f32)) -> Result<String, String> {
    run_child(&["import".as_ref(), source.as_os_str()], &mut progress)
}

/// Makes the rotated frame file for `id` in a child process.
pub fn make_rotated(id: &str, extra_rotation: u16) -> Result<(), String> {
    run_child(&["rotate-item".as_ref(), id.as_ref(), extra_rotation.to_string().as_ref()], &mut |_| {}).map(|_| ())
}

/// Child protocol on stdout: `progress <0..1>` lines, then `done <result>` or `error <message>`.
fn run_child(args: &[&std::ffi::OsStr], progress: &mut dyn FnMut(f32)) -> Result<String, String> {
    let exe = std::env::current_exe().map_err(|e| e.to_string())?;
    let mut child = Command::new(exe)
        .args(args)
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::null())
        .creation_flags(CREATE_NO_WINDOW)
        .spawn()
        .map_err(|e| e.to_string())?;
    let stdout = child.stdout.take().expect("piped stdout");
    let mut outcome = Err("converter exited unexpectedly".to_string());
    for line in BufReader::new(stdout).lines().map_while(Result::ok) {
        if let Some(p) = line.strip_prefix("progress ") {
            progress(p.parse().unwrap_or(0.0));
        } else if let Some(v) = line.strip_prefix("done ") {
            outcome = Ok(v.to_string());
        } else if let Some(e) = line.strip_prefix("error ") {
            outcome = Err(e.to_string());
        }
    }
    let _ = child.wait();
    outcome
}

/// Child side of `import`: converts `source` into a new gallery item.
pub fn import_in_process(source: &Path) -> Result<String, String> {
    let report = |p: f32| {
        println!("progress {p:.3}");
        let _ = io::stdout().flush();
    };
    let media = media::load_with_progress(source, 0.0, report)?;
    let frames: Vec<(Vec<u8>, Duration)> = match &media {
        Media::Still(canvas) => vec![(render::to_jpeg(canvas), Duration::ZERO)],
        Media::Animated(a) => a.frames.iter().map(|f| (f.wire.clone(), f.delay)).collect(),
    };
    let poster = match &media {
        Media::Still(canvas) => canvas,
        Media::Animated(a) => &a.poster,
    };

    let id = new_id();
    let dir = item_dir(&id);
    // Write into a temporary folder so `list` never sees a half-written item.
    let tmp = root().join(format!(".{id}.tmp"));
    let write = || -> io::Result<u64> {
        fs::create_dir_all(&tmp)?;
        let bytes = FrameFile::write(&tmp.join("frames.bin"), &frames)?;
        fs::write(tmp.join("thumb.jpg"), thumbnail(poster))?;
        let name = source.file_stem().map(|s| s.to_string_lossy().into_owned()).unwrap_or_else(|| id.clone());
        let duration: Duration = frames.iter().map(|(_, d)| *d).sum();
        let added = SystemTime::now().duration_since(UNIX_EPOCH).unwrap_or_default().as_secs();
        let info = format!(
            "name={}\nsource={}\nframes={}\nduration_ms={}\nbytes={bytes}\nadded={added}\ntruncated={}\nmax_fps={}\n",
            name.replace('\n', " "),
            source.display(),
            frames.len(),
            duration.as_millis(),
            matches!(&media, Media::Animated(a) if a.truncated),
            media::MAX_FPS,
        );
        fs::write(tmp.join("info.txt"), info)?;
        fs::rename(&tmp, &dir)?;
        Ok(bytes)
    };
    write().map_err(|e| {
        let _ = fs::remove_dir_all(&tmp);
        e.to_string()
    })?;
    Ok(id)
}

/// Child side of `rotate-item`: re-encodes the frames rotated by `extra_rotation` degrees.
pub fn rotate_in_process(id: &str, extra_rotation: u16) -> Result<String, String> {
    let src = FrameFile::open(&frames_path(id, 0)).map_err(|e| e.to_string())?;
    let mut frames = Vec::with_capacity(src.len());
    for i in 0..src.len() {
        let jpeg = src.read(i).map_err(|e| e.to_string())?;
        let canvas = decode_frame(&jpeg).map_err(|e| e.to_string())?;
        frames.push((render::to_jpeg(&render::rotate(&canvas, extra_rotation as f32)), src.delay(i)));
    }
    let out = frames_path(id, extra_rotation);
    let tmp = out.with_extension("tmp");
    FrameFile::write(&tmp, &frames).and_then(|_| fs::rename(&tmp, &out)).map_err(|e| e.to_string())?;
    Ok(id.to_string())
}

/// Decodes a stored 480x480 JPEG frame back into a canvas (for previews and rotation).
pub fn decode_frame(jpeg: &[u8]) -> image::ImageResult<Pixmap> {
    let img = image::load_from_memory_with_format(jpeg, image::ImageFormat::Jpeg)?;
    Ok(render::fit_to_canvas(img, FilterType::Triangle))
}

fn thumbnail(canvas: &Pixmap) -> Vec<u8> {
    let img = image::RgbaImage::from_raw(render::SIZE, render::SIZE, canvas.data().to_vec()).expect("canvas size");
    let small = image::imageops::resize(&img, THUMB_SIZE, THUMB_SIZE, FilterType::Triangle);
    let mut out = Vec::new();
    jpeg_encoder::Encoder::new(&mut out, 85)
        .encode(small.as_raw(), THUMB_SIZE as u16, THUMB_SIZE as u16, jpeg_encoder::ColorType::Rgba)
        .expect("in-memory encode");
    out
}

/// `MAGIC, count: u32, count * (offset: u64, len: u32, delay_ms: u32), JPEG data...` (little endian).
/// Only the index stays in memory; frames are read when they are sent.
pub struct FrameFile {
    file: File,
    index: Vec<(u64, u32, Duration)>,
}

impl FrameFile {
    pub fn write(path: &Path, frames: &[(Vec<u8>, Duration)]) -> io::Result<u64> {
        let header_len = 8 + frames.len() * 16;
        let mut out = Vec::with_capacity(header_len);
        out.extend_from_slice(MAGIC);
        out.extend_from_slice(&(frames.len() as u32).to_le_bytes());
        let mut offset = header_len as u64;
        for (jpeg, delay) in frames {
            out.extend_from_slice(&offset.to_le_bytes());
            out.extend_from_slice(&(jpeg.len() as u32).to_le_bytes());
            out.extend_from_slice(&(delay.as_millis() as u32).to_le_bytes());
            offset += jpeg.len() as u64;
        }
        let mut f = io::BufWriter::new(File::create(path)?);
        f.write_all(&out)?;
        for (jpeg, _) in frames {
            f.write_all(jpeg)?;
        }
        f.flush()?;
        Ok(offset)
    }

    pub fn open(path: &Path) -> io::Result<FrameFile> {
        let mut file = File::open(path)?;
        let mut head = [0u8; 8];
        file.read_exact(&mut head)?;
        if &head[..4] != MAGIC {
            return Err(io::Error::new(io::ErrorKind::InvalidData, "not a frame file"));
        }
        let count = u32::from_le_bytes(head[4..8].try_into().expect("4 bytes")) as usize;
        let mut raw = vec![0u8; count * 16];
        file.read_exact(&mut raw)?;
        let index = raw
            .chunks_exact(16)
            .map(|e| {
                let offset = u64::from_le_bytes(e[0..8].try_into().expect("8 bytes"));
                let len = u32::from_le_bytes(e[8..12].try_into().expect("4 bytes"));
                let delay = u32::from_le_bytes(e[12..16].try_into().expect("4 bytes"));
                (offset, len, Duration::from_millis(delay as u64))
            })
            .collect::<Vec<_>>();
        if index.is_empty() {
            return Err(io::Error::new(io::ErrorKind::InvalidData, "empty frame file"));
        }
        Ok(FrameFile { file, index })
    }

    pub fn len(&self) -> usize {
        self.index.len()
    }

    pub fn delay(&self, i: usize) -> Duration {
        self.index[i].2
    }

    pub fn read(&self, i: usize) -> io::Result<Vec<u8>> {
        let mut buf = Vec::new();
        self.read_into(i, &mut buf)?;
        Ok(buf)
    }

    pub fn read_into(&self, i: usize, buf: &mut Vec<u8>) -> io::Result<()> {
        let (offset, len, _) = self.index[i];
        buf.resize(len as usize, 0);
        let mut done = 0;
        while done < buf.len() {
            match self.file.seek_read(&mut buf[done..], offset + done as u64)? {
                0 => return Err(io::ErrorKind::UnexpectedEof.into()),
                n => done += n,
            }
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn frame_file_round_trip() {
        let path = std::env::temp_dir().join("atmos-lcd-frames.bin");
        let frames = vec![(vec![1, 2, 3], Duration::from_millis(66)), (vec![9; 1000], Duration::from_millis(100))];
        let bytes = FrameFile::write(&path, &frames).unwrap();
        assert_eq!(bytes, fs::metadata(&path).unwrap().len());
        let f = FrameFile::open(&path).unwrap();
        assert_eq!(f.len(), 2);
        assert_eq!(f.read(1).unwrap(), vec![9; 1000]);
        assert_eq!(f.delay(0), Duration::from_millis(66));
        let _ = fs::remove_file(path);
    }
}
